def get_sb_odds() -> dict:
    from collections import defaultdict

    sums = defaultdict(lambda: 0)
    sum_points = 0
    for bet in BETS:
        sum_bet = 0
        for team, points in bet.points.items():
            sums[team] += points
            sum_bet += points
        assert sum_bet == 105
        sum_points += sum_bet
    odds = {}
    for team, points in sums.items():
        odds[team] = points / sum_points
    return odds
